export const PUSH_FAILURE_KIND = {
  DEVICE_UNREGISTERED: "DEVICE_UNREGISTERED",
  INVALID_TOKEN: "INVALID_TOKEN",
  PAYLOAD_TOO_LARGE: "PAYLOAD_TOO_LARGE",
  RATE_LIMITED: "RATE_LIMITED",
  PROVIDER_REJECTED: "PROVIDER_REJECTED",
  PROVIDER_UNAVAILABLE: "PROVIDER_UNAVAILABLE",
  RECEIPT_EXPIRED: "RECEIPT_EXPIRED",
  UNKNOWN: "UNKNOWN",
} as const;

export type PushFailureKind = (typeof PUSH_FAILURE_KIND)[keyof typeof PUSH_FAILURE_KIND];

const TOKEN_REVOKING_FAILURE_KINDS: ReadonlySet<PushFailureKind> = new Set([
  PUSH_FAILURE_KIND.DEVICE_UNREGISTERED,
  PUSH_FAILURE_KIND.INVALID_TOKEN,
]);

export function revokesPushToken(kind: PushFailureKind): boolean {
  return TOKEN_REVOKING_FAILURE_KINDS.has(kind);
}
